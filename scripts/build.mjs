import fs from 'node:fs/promises';
import path from 'node:path';
import {validate} from './validate.mjs';
const {products}=await validate();
await fs.mkdir('dist',{recursive:true});
await fs.cp('site','dist',{recursive:true});
await fs.writeFile('dist/catalog.mjs','// Generated by scripts/build.mjs. Edit data/brands/*.json instead.\nexport default '+JSON.stringify(products)+';\n');
await fs.writeFile('dist/.nojekyll','');
console.log(`Built ${products.length} records -> ${path.resolve('dist')}`);
